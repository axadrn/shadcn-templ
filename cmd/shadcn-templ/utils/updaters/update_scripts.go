package updaters

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"github.com/axadrn/shadcn-templ/v2/cmd/shadcn-templ/utils"
)

// UpdateScripts builds the component asset and its Go URL manifest at build
// time. The asset only depends on the shared component scripts, so every app
// of the module whose aliases.components resolve to the same directory gets
// the same bytes: it is written into each app's scripts.dir, and the one
// manifest in the components package is correct for all of them as long as
// they serve it under the same scripts.path. paths lists the written asset
// of config's app first, then the other apps' assets.
func UpdateScripts(config *utils.Config) (paths []string, written bool, err error) {
	shared, err := utils.GetSharedConfigs(config)
	if err != nil {
		return nil, false, err
	}
	urlPrefix := strings.TrimRight(config.Scripts.Path, "/")
	dirs := []string{config.ResolvedPaths.Scripts}
	for _, other := range shared {
		if prefix := strings.TrimRight(other.Scripts.Path, "/"); prefix != urlPrefix {
			return nil, false, fmt.Errorf("%s and %s share the components package %s but configure different scripts.path (%q and %q); its scripts_bundle.go holds one URL, so use the same scripts.path or separate aliases.components",
				filepath.Join(config.ResolvedPaths.Cwd, utils.ConfigFileName), filepath.Join(other.ResolvedPaths.Cwd, utils.ConfigFileName), config.Aliases.Components, config.Scripts.Path, other.Scripts.Path)
		}
		if !slices.Contains(dirs, other.ResolvedPaths.Scripts) {
			dirs = append(dirs, other.ResolvedPaths.Scripts)
		}
	}

	files, err := filepath.Glob(filepath.Join(config.ResolvedPaths.Components, "*", "*.js"))
	if err != nil {
		return nil, false, err
	}
	// The shared blocks in baseui come first, since components register with
	// them while the bundle loads. Otherwise lexical order, which keeps
	// floating_ui_core before floating_ui_dom.
	sort.SliceStable(files, func(i, j int) bool {
		return isBaseUI(files[i]) && !isBaseUI(files[j])
	})
	var bundle bytes.Buffer
	for _, file := range files {
		if strings.HasSuffix(file, ".min.js") {
			continue
		}
		data, err := os.ReadFile(file)
		if err != nil {
			return nil, false, err
		}
		rel, err := filepath.Rel(config.ResolvedPaths.Components, file)
		if err != nil {
			return nil, false, err
		}
		fmt.Fprintf(&bundle, "// components/%s\n", filepath.ToSlash(rel))
		bundle.Write(data)
		bundle.WriteByte('\n')
	}
	sum := sha256.Sum256(bundle.Bytes())
	name := fmt.Sprintf("shadcn-templ-%x.js", sum[:8])
	src := urlPrefix + "/" + name
	manifest, err := format.Source(fmt.Appendf(nil, "// Code generated by shadcn-templ bundle. DO NOT EDIT.\n\npackage %s\n\nconst bundleSrc = %q\n", lastSegment(config.Aliases.Components), src))
	if err != nil {
		return nil, false, err
	}
	// Assets first, so the manifest never names a file that is not there yet.
	for _, dir := range dirs {
		path := filepath.Join(dir, name)
		paths = append(paths, path)
		changed, err := writeChanged(path, bundle.Bytes())
		if err != nil {
			return paths, written, err
		}
		written = written || changed
	}
	changed, err := writeChanged(filepath.Join(config.ResolvedPaths.Components, "scripts_bundle.go"), manifest)
	if err != nil {
		return paths, written, err
	}
	written = written || changed
	for _, dir := range dirs {
		stale, err := filepath.Glob(filepath.Join(dir, "shadcn-templ-*.js"))
		if err != nil {
			return paths, written, err
		}
		for _, old := range stale {
			if filepath.Base(old) != name {
				if err := os.Remove(old); err != nil {
					return paths, written, err
				}
				written = true
			}
		}
	}
	if config.ScriptsDefaulted {
		if err := utils.WriteConfig(config.ResolvedPaths.Cwd, &config.RawConfig); err != nil {
			return paths, written, err
		}
		config.ScriptsDefaulted = false
	}
	return paths, written, nil
}

func writeChanged(path string, data []byte) (bool, error) {
	existing, err := os.ReadFile(path)
	if err == nil && bytes.Equal(existing, data) {
		return false, nil
	}
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return false, err
	}
	// Rename prevents readers from seeing a partially written asset or manifest.
	f, err := os.CreateTemp(filepath.Dir(path), ".bundle-*")
	if err != nil {
		return false, err
	}
	defer os.Remove(f.Name())
	if _, err := f.Write(data); err != nil {
		f.Close()
		return false, err
	}
	if err := f.Chmod(0644); err != nil {
		f.Close()
		return false, err
	}
	if err := f.Close(); err != nil {
		return false, err
	}
	if err := os.Rename(f.Name(), path); err != nil {
		return false, err
	}
	return true, nil
}

func isBaseUI(file string) bool {
	return filepath.Base(filepath.Dir(file)) == "baseui"
}
